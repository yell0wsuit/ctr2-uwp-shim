#!/usr/bin/env python3
"""Generate HRESULT-only defaults from SDK MIDL C++ declarations.

Unlike a WinMD projection, signatures are copied from the compiler's ABI header.
Unsupported/missing contracts are errors. Compile the output against the same SDK.
"""
import argparse
import pathlib
import re


def generate(text, header, interfaces):
    text = re.sub(r'/\*.*?\*/|//[^\n]*', '', text, flags=re.S)
    text = re.sub(r'^\s*#.*$', '', text, flags=re.M)
    text = re.sub(r'DEPRECATED\("[^"]*"\)', '', text)
    output = ['// Generated by scripts/gen_stubs.py; do not edit.', '#pragma once',
              '#include <windows.h>', '#undef GetCurrentTime', f'#include <{header}>', '#include "log.h"', '#pragma warning(push)', '#pragma warning(disable: 4100)']
    for qualified in interfaces:
        parts = qualified.split('::')
        name = parts[-1]
        pattern = r'MIDL_INTERFACE\("([^"\n]+)"\)\s*' + re.escape(name) + r'\s*:\s*public\s+IInspectable\s*\{(.*?)\};'
        found = re.search(pattern, text, re.S)
        if not found:
            raise ValueError(f'{qualified} not found as a direct IInspectable interface')
        uuid = found.group(1)
        body = found.group(2)
        methods = re.findall(r'virtual\s+HRESULT\s+STDMETHODCALLTYPE\s+(\w+)\s*\((.*?)\)\s*=\s*0\s*;', body, re.S)
        if not methods or len(methods) != len(re.findall(r'\bvirtual\b', body)):
            raise ValueError(f'{qualified}: unsupported ABI declaration')
        output += [f'namespace {"::".join(parts[:-1])} {{',
                   f'struct __declspec(uuid("{uuid}")) Default{name} : public {qualified} {{']
        for method, args in methods:
            args = re.sub(r'\s+', ' ', args).strip()
            output += [f'  HRESULT STDMETHODCALLTYPE {method}({args}) override {{',
                       f'    ctr2::Log("UNIMPL", "{qualified}::{method}");',
                       '    return E_NOTIMPL;', '  }']
        output += ['};', '}']
    output += ['#pragma warning(pop)']
    return '\n'.join(output) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('header', type=pathlib.Path)
    parser.add_argument('output', type=pathlib.Path)
    parser.add_argument('interfaces', nargs='+')
    args = parser.parse_args()
    result = generate(args.header.read_text(encoding='utf-8-sig'), args.header.name, args.interfaces)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(result)


if __name__ == '__main__':
    main()
