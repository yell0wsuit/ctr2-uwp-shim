#!/usr/bin/env python3
"""Emit x86 register-preserving lazy tail thunks (MSVC/clang-cl inline asm)."""
import pathlib

root = pathlib.Path(__file__).resolve().parents[1]
names = (root / 'proxy/d3dcompiler_47/exports.txt').read_text().splitlines()
source = ['// Generated by scripts/gen_proxy.py', '#include <windows.h>',
          f'extern "C" void* ctr2_targets[{len(names)}];', 'extern "C" void __cdecl ctr2_resolve(unsigned index);']
definition = ['LIBRARY d3dcompiler_47', 'EXPORTS']
for index, name in enumerate(names):
    source += [f'extern "C" __declspec(naked) void proxy_{name}() {{',
               '  __asm {', '    pushfd', '    pushad', f'    push {index}',
               '    call ctr2_resolve', '    add esp, 4', '    popad', '    popfd',
               f'    jmp dword ptr [ctr2_targets + {index * 4}]', '  }', '}']
    definition += [f'  {name}=proxy_{name} @{index + 1}']
source += ['extern "C" const char* ctr2_export_names[] = {']
source += [f'  "{name}",' for name in names]
source += ['};', f'extern "C" void* ctr2_targets[{len(names)}] = {{}};']
(root / 'proxy/d3dcompiler_47/thunks.cpp').write_text('\n'.join(source) + '\n')
(root / 'proxy/d3dcompiler_47/proxy.def').write_text('\n'.join(definition) + '\n')
